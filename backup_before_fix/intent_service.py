# ==============================================
# NORMALIZE QUESTION
# ==============================================

def normalize_question(question):

    """
    ทำความสะอาดข้อความเบื้องต้น
    """

    if not question:
        return ""

    question = question.lower().strip()

    # ลดช่องว่างซ้ำ
    question = re.sub(
        r"\s+",
        " ",
        question
    )

    return question


# ==============================================
# DETECT INTENT
# ==============================================

def detect_intent(question):

    """
    ตรวจจับ Learning Intent

    Returns
    -------
    dict หรือ None

    ตัวอย่าง:

    {
        "lg_id": "LG03",
        "matched_pattern": "เริ่ม.*ยังไง",
        "source": "RULE_BASED_INTENT"
    }
    """

    question = normalize_question(question)

    if not question:
        return None


    # ------------------------------------------
    # Check by Priority
    # ------------------------------------------

    for lg_id in INTENT_PRIORITY:

        patterns = INTENT_PATTERNS.get(
            lg_id,
            []
        )

        for pattern in patterns:

            if re.search(
                pattern,
                question,
                re.IGNORECASE
            ):

                return {

                    "lg_id": lg_id,

                    "matched_pattern": pattern,

                    "source": "RULE_BASED_INTENT"

                }


    # ------------------------------------------
    # No Intent Detected
    # ------------------------------------------

    return None